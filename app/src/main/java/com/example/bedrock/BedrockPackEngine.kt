    fun toFirestoreDocId(packType: PackType, relativePath: String): String {
        val raw = "${packType.folderPrefix}_${relativePath.lowercase(Locale.US)}"
            .replace(Regex("[^a-z0-9_\\-]"), "_")
            .replace(Regex("_+"), "_")
            .trim('_')
        return if (raw.length <= 120) raw.ifEmpty { "file_${UUID.randomUUID().toString().take(8)}" }
        else raw.take(100) + "_" + raw.hashCode().toUInt().toString(16)
    }

    fun sanitizeNamespace(raw: String): String {
        val cleaned = raw.lowercase(Locale.US)
            .replace(Regex("[^a-z0-9_]"), "_")
            .replace(Regex("_+"), "_")
            .trim('_')
        val candidate = if (cleaned.length < 2) "custom_mod" else cleaned.take(32)
        return if (candidate in setOf("minecraft", "minecon", "realms")) "${candidate}_addon" else candidate
    }

    fun sanitizeFileName(raw: String): String =
        raw.trim().replace(Regex("[^a-zA-Z0-9_\\-]"), "_").replace(Regex("_+"), "_").ifBlank { "minecraft_mod" }

    fun buildBehaviorManifestJson(project: ModProject): String {
        val moduleUuid = UUID.nameUUIDFromBytes("${project.bpUuid}:data".toByteArray()).toString()
        val manifest = JSONObject().apply {
            put("format_version", 2)
            put("header", JSONObject().apply {
                put("name", "${project.name} BP")
                put("description", project.description.ifBlank { "Generated by Minecraft AI Mod Maker Studio" })
                put("uuid", project.bpUuid)
                put("version", JSONArray(listOf(1, 0, 0)))
                put("min_engine_version", JSONArray(listOf(1, 21, 50)))
            })
            put("modules", JSONArray().apply {
                put(JSONObject().apply {
                    put("type", "data")
                    put("uuid", moduleUuid)
                    put("version", JSONArray(listOf(1, 0, 0)))
                })
            })
            put("dependencies", JSONArray().apply {
                put(JSONObject().apply {
                    put("uuid", project.rpUuid)
                    put("version", JSONArray(listOf(1, 0, 0)))
                })
            })
        }
        return manifest.toString(2)
    }

    fun buildResourceManifestJson(project: ModProject): String {
        val moduleUuid = UUID.nameUUIDFromBytes("${project.rpUuid}:resources".toByteArray()).toString()
        val manifest = JSONObject().apply {
            put("format_version", 2)
            put("header", JSONObject().apply {
                put("name", "${project.name} RP")
                put("description", project.description.ifBlank { "Resource Pack generated by Minecraft AI Mod Maker Studio" })
                put("uuid", project.rpUuid)
                put("version", JSONArray(listOf(1, 0, 0)))
                put("min_engine_version", JSONArray(listOf(1, 21, 50)))
            })
            put("modules", JSONArray().apply {
                put(JSONObject().apply {
                    put("type", "resources")
                    put("uuid", moduleUuid)
                    put("version", JSONArray(listOf(1, 0, 0)))
                })
            })
        }
        return manifest.toString(2)
    }

    fun ensureManifestFiles(
        project: ModProject,
        existingFiles: List<ModFileEntry>,
        userId: String
    ): List<ModFileEntry> {
        val mutable = existingFiles.associateBy {
            "${it.resolvedPackType.name}:${it.relativePath}"
        }.toMutableMap()

        val bpManifestKey = "${PackType.BEHAVIOR_PACK.name}:manifest.json"
        if (!mutable.containsKey(bpManifestKey)) {
            mutable[bpManifestKey] = ModFileEntry(
                id = toFirestoreDocId(PackType.BEHAVIOR_PACK, "manifest.json"),
                userId = userId,
                projectId = project.id,
                packType = PackType.BEHAVIOR_PACK.name,
                relativePath = "manifest.json",
                contentText = buildBehaviorManifestJson(project),
                textureBase64 = "",
                valid = true,
                validationNotes = ""
            )
        }

        val rpManifestKey = "${PackType.RESOURCE_PACK.name}:manifest.json"
        if (!mutable.containsKey(rpManifestKey)) {
            mutable[rpManifestKey] = ModFileEntry(
                id = toFirestoreDocId(PackType.RESOURCE_PACK, "manifest.json"),
                userId = userId,
                projectId = project.id,
                packType = PackType.RESOURCE_PACK.name,
                relativePath = "manifest.json",
                contentText = buildResourceManifestJson(project),
                textureBase64 = "",
                valid = true,
                validationNotes = ""
            )
        }

        return mutable.values.sortedWith(
            compareBy<ModFileEntry> { it.resolvedPackType.name }.thenBy { it.relativePath }
        )
    }

    fun validatePackFiles(files: List<ModFileEntry>): ValidationSummaryResult {
        if (files.isEmpty()) {
            return ValidationSummaryResult(
                files = emptyList(),
                errorCount = 0L,
                summaryText = "No pack files generated yet. Describe your mod idea in chat to begin."
            )
        }

        var errors = 0L
        val errorNotes = mutableListOf<String>()

        val hasBpManifest = files.any { it.resolvedPackType == PackType.BEHAVIOR_PACK && it.relativePath == "manifest.json" }
        val hasRpManifest = files.any { it.resolvedPackType == PackType.RESOURCE_PACK && it.relativePath == "manifest.json" }
        if (!hasBpManifest) {
            errors++
            errorNotes.add("Missing BP/manifest.json")
        }
        if (!hasRpManifest) {
            errors++
            errorNotes.add("Missing RP/manifest.json")
        }

        val validated = files.map { entry ->
            val pathLower = entry.relativePath.lowercase(Locale.US)
            if (pathLower.endsWith(".png")) {
                val hasBytes = entry.textureBase64.isNotBlank()
                if (!hasBytes) {
                    entry.copy(valid = true, validationNotes = "Texture placeholder — tap Generate Texture or ask AI to paint it.")
                } else {
                    entry.copy(valid = true, validationNotes = "")
                }
            } else if (pathLower.endsWith(".json")) {
                val diagnostic = validateBedrockJson(entry.resolvedPackType, entry.relativePath, entry.contentText)
                if (diagnostic != null) {
                    errors++
                    errorNotes.add("${entry.resolvedPackType.folderPrefix}/${entry.relativePath}: $diagnostic")
                    entry.copy(valid = false, validationNotes = diagnostic)
                } else {
                    entry.copy(valid = true, validationNotes = "")
                }
            } else {
                if (entry.contentText.isBlank()) {
                    errors++
                    val msg = "File content is empty."
                    errorNotes.add("${entry.resolvedPackType.folderPrefix}/${entry.relativePath}: $msg")
                    entry.copy(valid = false, validationNotes = msg)
                } else {
                    entry.copy(valid = true, validationNotes = "")
                }
            }
        }

        val summary = if (errors == 0L) {
            "All ${validated.size} Behavior & Resource Pack files validated cleanly for Bedrock Edition."
        } else {
            val preview = errorNotes.take(4).joinToString(" • ")
            "$errors issue${if (errors == 1L) "" else "s"} detected: $preview"
        }

        return ValidationSummaryResult(
            files = validated,
            errorCount = errors,
            summaryText = summary
        )
    }

    private fun validateBedrockJson(packType: PackType, relativePath: String, content: String): String? {
        if (content.isBlank()) return "JSON file is empty."
        val root = try {
            val trimmed = content.trim()
            if (trimmed.startsWith("[")) {
                JSONArray(trimmed)
                return null
            } else {
                JSONObject(trimmed)
            }
        } catch (e: Exception) {
            return "Invalid JSON syntax: ${e.message ?: "Parse failure"}"
        }

        val pathLower = relativePath.lowercase(Locale.US)
        if (pathLower == "manifest.json") {
            if (!root.has("format_version")) return "manifest.json missing format_version"
            val header = root.optJSONObject("header") ?: return "manifest.json missing header object"
            if (header.optString("uuid").isBlank()) return "manifest.json header.uuid is missing"
            val modules = root.optJSONArray("modules")
            if (modules == null || modules.length() == 0) return "manifest.json requires at least one module"
            return null
        }

        val requiresFormatVersion = pathLower.startsWith("blocks/") ||
            pathLower.startsWith("entities/") ||
            pathLower.startsWith("items/") ||
            pathLower.startsWith("recipes/") ||
            pathLower.startsWith("spawn_rules/") ||
            pathLower.startsWith("entity/") ||
            pathLower.startsWith("models/entity/") ||
            pathLower.startsWith("animations/") ||
            pathLower.startsWith("animation_controllers/") ||
            pathLower.startsWith("render_controllers/")

        if (requiresFormatVersion && !root.has("format_version")) {
            return "Missing Bedrock 'format_version' field."
        }

        if (packType == PackType.BEHAVIOR_PACK) {
            when {
                pathLower.startsWith("blocks/") -> {
                    val blockObj = root.optJSONObject("minecraft:block")
                        ?: return "Missing 'minecraft:block' root object."
                    val id = blockObj.optJSONObject("description")?.optString("identifier").orEmpty()
                    if (!id.contains(":")) return "Block identifier '$id' must include namespace:name."
                }
                pathLower.startsWith("entities/") -> {
                    val entityObj = root.optJSONObject("minecraft:entity")
                        ?: return "Missing 'minecraft:entity' root object."
                    val id = entityObj.optJSONObject("description")?.optString("identifier").orEmpty()
                    if (!id.contains(":")) return "Entity identifier '$id' must include namespace:name."
                }
                pathLower.startsWith("items/") -> {
                    val itemObj = root.optJSONObject("minecraft:item")
                        ?: return "Missing 'minecraft:item' root object."
                    val id = itemObj.optJSONObject("description")?.optString("identifier").orEmpty()
                    if (!id.contains(":")) return "Item identifier '$id' must include namespace:name."
                }
            }
        }
        return null
    }

    fun computeComponentCounts(files: List<ModFileEntry>): ComponentCounts {
        var blocks = 0L
        var mobs = 0L
        var weapons = 0L
        var armor = 0L
        var items = 0L
        var structures = 0L
        var recipes = 0L
        var textures = 0L

        for (file in files) {
            val path = file.relativePath.lowercase(Locale.US)
            val isBp = file.resolvedPackType == PackType.BEHAVIOR_PACK
            when {
                isBp && path.startsWith("blocks/") && path.endsWith(".json") -> blocks++
                isBp && path.startsWith("entities/") && path.endsWith(".json") -> mobs++
                isBp && path.startsWith("recipes/") && path.endsWith(".json") -> recipes++
                isBp && (path.startsWith("structures/") || path.startsWith("features/") || path.startsWith("feature_rules/") || path.startsWith("functions/")) -> structures++
                isBp && path.startsWith("items/") && path.endsWith(".json") -> {
                    val textLower = file.contentText.lowercase(Locale.US)
                    when {
                        textLower.contains("minecraft:weapon") || textLower.contains("minecraft:damage") || path.contains("sword") || path.contains("axe") || path.contains("bow") || path.contains("blade") || path.contains("staff") -> weapons++
                        textLower.contains("minecraft:wearable") || path.contains("helmet") || path.contains("chestplate") || path.contains("leggings") || path.contains("boots") || path.contains("armor") -> armor++
                        else -> items++
                    }
                }
                !isBp && path.startsWith("textures/") && path.endsWith(".png") && file.textureBase64.isNotBlank() -> textures++
            }
        }

        return ComponentCounts(
            blocksCount = blocks,
            mobsCount = mobs,
            weaponsCount = weapons,
            armorCount = armor,
            itemsCount = items,
            structuresCount = structures,
            recipesCount = recipes,
            texturesCount = textures
        )
    }

    fun pixelateBitmapToPngBase64(bitmap: Bitmap, sizePx: Int = 32): String {
        val scaled = Bitmap.createBitmap(sizePx, sizePx, Bitmap.Config.ARGB_8888)
        val canvas = Canvas(scaled)
        val paint = Paint().apply {
            isFilterBitmap = false
            isAntiAlias = false
        }
        val destRect = android.graphics.Rect(0, 0, sizePx, sizePx)
        canvas.drawBitmap(bitmap, null, destRect, paint)
        val out = ByteArrayOutputStream()
        scaled.compress(Bitmap.CompressFormat.PNG, 100, out)
        return Base64.encodeToString(out.toByteArray(), Base64.NO_WRAP)
    }

    fun decodeBase64Bitmap(base64: String): Bitmap? {
        if (base64.isBlank()) return null
        return try {
            val bytes = Base64.decode(base64, Base64.DEFAULT)
            BitmapFactory.decodeByteArray(bytes, 0, bytes.size)
        } catch (_: Exception) {
            null
        }
    }

    fun writeArchive(
        project: ModProject,
        rawFiles: List<ModFileEntry>,
        format: ExportFormat,
        outputStream: OutputStream
    ) {
        val files = ensureManifestFiles(project, rawFiles, project.userId)
        val safeBase = sanitizeFileName(project.name)
        val bpFiles = files.filter { it.resolvedPackType == PackType.BEHAVIOR_PACK }
        val rpFiles = files.filter { it.resolvedPackType == PackType.RESOURCE_PACK }

        ZipOutputStream(outputStream).use { zip ->
            when (format) {
                ExportFormat.MCADDON -> {
                    writePackToZip(zip, "${safeBase}_BP/", bpFiles)
                    writePackToZip(zip, "${safeBase}_RP/", rpFiles)
                }
                ExportFormat.MCPACK_BP -> {
                    writePackToZip(zip, "", bpFiles)
                }
                ExportFormat.MCPACK_RP -> {
                    writePackToZip(zip, "", rpFiles)
                }
                ExportFormat.ZIP -> {
                    writePackToZip(zip, "${safeBase}/BP/", bpFiles)
                    writePackToZip(zip, "${safeBase}/RP/", rpFiles)
                    val readme = buildString {
                        appendLine("# ${project.name}")
                        appendLine("Namespace: ${project.namespace}")
                        appendLine("Target Bedrock Version: ${project.targetVersion}")
                        appendLine("BP UUID: ${project.bpUuid}")
                        appendLine("RP UUID: ${project.rpUuid}")
                        appendLine()
                        appendLine(project.description)
                        appendLine()
                        appendLine("Validation: ${project.validationSummary}")
                    }
                    zip.putNextEntry(ZipEntry("${safeBase}/README.txt"))
                    zip.write(readme.toByteArray(Charsets.UTF_8))
                    zip.closeEntry()
                }
            }
        }
    }

    private fun writePackToZip(
        zip: ZipOutputStream,
        prefix: String,
        entries: List<ModFileEntry>
    ) {
        for (entry in entries) {
            val cleanPath = entry.relativePath.trimStart('/')
            val fullPath = "$prefix$cleanPath"
            if (entry.relativePath.endsWith(".png", ignoreCase = true)) {
                if (entry.textureBase64.isNotBlank()) {
                    val bytes = Base64.decode(entry.textureBase64, Base64.DEFAULT)
                    zip.putNextEntry(ZipEntry(fullPath))
                    zip.write(bytes)
                    zip.closeEntry()
                }
            } else {
                zip.putNextEntry(ZipEntry(fullPath))
                zip.write(entry.contentText.toByteArray(Charsets.UTF_8))
                zip.closeEntry()
            }
        }
    }

    fun exportToCacheAndGetUri(
        context: Context,
        project: ModProject,
        files: List<ModFileEntry>,
        format: ExportFormat
    ): Uri {
        val exportsDir = File(context.cacheDir, "exports").apply { mkdirs() }
        val suffix = when (format) {
            ExportFormat.MCPACK_BP -> "_BP.mcpack"
            ExportFormat.MCPACK_RP -> "_RP.mcpack"
            ExportFormat.MCADDON -> ".mcaddon"
            ExportFormat.ZIP -> "_project.zip"
        }
        val outFile = File(exportsDir, "${sanitizeFileName(project.name)}$suffix")
        FileOutputStream(outFile).use { fos ->
            writeArchive(project, files, format, fos)
        }
        return FileProvider.getUriForFile(
            context,
            "${context.packageName}.fileprovider",
            outFile
        )
    }

    fun extractAttachmentSummary(
        context: Context,
        uri: Uri,
        fileName: String
    ): String {
        val lower = fileName.lowercase(Locale.US)
        return context.contentResolver.openInputStream(uri)?.use { input ->
            if (lower.endsWith(".zip") || lower.endsWith(".mcpack") || lower.endsWith(".mcaddon")) {
                val builder = StringBuilder()
                builder.appendLine("Imported archive: $fileName")
                ZipInputStream(input).use { zis ->
                    var count = 0
                    var entry = zis.nextEntry
                    while (entry != null && count < 18) {
                        if (!entry.isDirectory) {
                            builder.appendLine("- ${entry.name}")
                            if (entry.name.endsWith(".json", ignoreCase = true) && count < 6) {
                                val text = zis.readBytes().toString(Charsets.UTF_8).take(1200)
                                builder.appendLine("```json\n$text\n```")
                            }
                            count++
                        }
                        entry = zis.nextEntry
                    }
                }
                builder.toString().take(8000)
            } else {
                input.bufferedReader().readText().take(8000)
            }
        } ?: ""
    }
